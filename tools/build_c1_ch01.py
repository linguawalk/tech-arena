def par2(extra=None, sw=False):
    e = left_cell("6 V") + [W((0, 0), (3, 0)), W((0, 2), (3, 2)), P("lamp", (1.5, 0), (1.5, 2), "L1")]
    if sw:
        e += [P("switch", (3, 0), (3, 1)), P("lamp", (3, 1), (3, 2), "L2")]
    else:
        e += [P("lamp", (3, 0), (3, 2), "L2")]
    return circ(e + (extra or []), dots=[[1.5, 0], [1.5, 2]], alt="전구 L1과 L2가 나란히 연결된 회로도")

F_PAR2 = par2()
