def mix(names=("R1", "R2", "R3"), t="resistor"):
    return circ(left_cell("6 V") + [P(t, (0, 0), (2, 0), names[0]), W((2, 0), (4, 0)),
                                    P(t, (2, 0), (2, 2), names[1]), P(t, (4, 0), (4, 2), names[2]), W((4, 2), (0, 2))],
                dots=[[2, 0], [2, 2]], alt=f"{names[0]} 뒤에 {names[1]}와 {names[2]}가 나란히 연결된 회로도")

F_MIX = mix()
F_MIX3 = mix(("L1", "L2", "L3"), "lamp")


def meter(load="lamp", name="전구"):
    return circ(left_cell("6 V") + [P("ammeter", (0, 0), (2, 0)), W((2, 0), (4, 0)), P(load, (4, 0), (4, 2), name, side="b"),
                                    W((4, 2), (0, 2)), W((4, 0), (5.3, 0)), W((4, 2), (5.3, 2)), P("voltmeter", (5.3, 0), (5.3, 2))],
                dots=[[4, 0], [4, 2]], alt=f"전류계가 한 줄로, 전압계가 {name} 양 끝에 연결된 회로도")

F_METER = meter()
